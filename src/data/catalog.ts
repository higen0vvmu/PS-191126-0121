function part(
  id: string,
  name: string,
  shape: PartShape,
  xMm: number,
  yMm: number,
  zMm: number,
  widthMm: number,
  depthMm: number,
  heightMm: number,
  material: MaterialPreset,
  rotationDeg = 0,
  detailStyle?: PartDetailStyle,
  color = '#FFFFFF'
): FurniturePart {
  return {
    id,
    name,
    shape,
    xMm,
    yMm,
    zMm,
    widthMm,
    depthMm,
    heightMm,
    rotationDeg,
    color,
    material,
    detailStyle,
  };
}

